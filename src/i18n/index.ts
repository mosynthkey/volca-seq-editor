const stored = typeof localStorage !== 'undefined' ? localStorage.getItem('volca-seq-locale') : null;
const browserJa = typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('ja');

export const i18n = createI18n({
  legacy: false,
  locale: stored === 'en' || stored === 'ja' ? stored : (browserJa ? 'ja' : 'en'),
  fallbackLocale: 'en',
  messages,
});

export const setAppLocale = (locale: 'ja' | 'en') => {
  i18n.global.locale.value = locale;
  localStorage.setItem('volca-seq-locale', locale);
};
